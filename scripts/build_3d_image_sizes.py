#!/usr/bin/env python3
"""Makes small copies of every product photo for faster pages, and records
each photo's size so the store can use them.

For each image in 3d-products.json wider than 500 px it writes, next to it:
  <name>-500w.webp  shop cards and product photos on phones
  <name>-160w.webp  product-page thumbnails
and saves {"/3d/assets/images/products/x.webp": [width, height], ...} to
3d/assets/data/3d-image-sizes.json. It also refreshes the IMG_SIZES table in
3d/assets/js/3d-store.js (between the BEGIN/END markers).

Run it after adding product photos, then run generate_3d_static.py.
Usage: python scripts/build_3d_image_sizes.py
"""
import json
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PRODUCTS_JSON = os.path.join(ROOT, '3d', 'assets', 'data', '3d-products.json')
SIZES_JSON = os.path.join(ROOT, '3d', 'assets', 'data', '3d-image-sizes.json')
STORE_JS = os.path.join(ROOT, '3d', 'assets', 'js', '3d-store.js')
BEGIN = '/* BEGIN IMG_SIZES (generated by scripts/build_3d_image_sizes.py) */'
END = '/* END IMG_SIZES */'
WIDTHS = (500, 160)


def small_path(src, w):
    return re.sub(r'\.(webp|jpe?g|png)$', '-%dw.webp' % w, src, flags=re.I)


def catalog_images():
    with open(PRODUCTS_JSON, encoding='utf-8') as f:
        products = json.load(f)['products']
    seen = []
    for p in products:
        for src in (p.get('images') or []) + [p.get('cardImage')] + [v.get('image') for v in p.get('variants') or []]:
            if src and src.startswith('/3d/') and src not in seen:
                seen.append(src)
    return seen


def main():
    sizes, made = {}, 0
    for src in catalog_images():
        path = os.path.join(ROOT, src.lstrip('/'))
        if not os.path.isfile(path):
            continue
        with Image.open(path) as im:
            w, h = im.size
            if w <= 520:
                continue
            sizes[src] = [w, h]
            for tw in WIDTHS:
                out = os.path.join(ROOT, small_path(src, tw).lstrip('/'))
                if os.path.isfile(out) and os.path.getmtime(out) >= os.path.getmtime(path):
                    continue
                rgb = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
                rgb.resize((tw, round(h * tw / w)), Image.LANCZOS).save(out, 'WEBP', quality=80, method=6)
                made += 1
    with open(SIZES_JSON, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(sizes, f, indent=0, sort_keys=True)
        f.write('\n')
    # Keyed by file name in the store script (all product photos share one folder).
    table = ', '.join("'%s': [%d, %d]" % (os.path.basename(k), v[0], v[1]) for k, v in sorted(sizes.items()))
    with open(STORE_JS, encoding='utf-8') as f:
        js = f.read()
    block = BEGIN + '\n  var IMG_SIZES = {' + table + '};\n  ' + END
    js, n = re.subn(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: block, js, count=1, flags=re.S)
    if n != 1:
        raise SystemExit('IMG_SIZES markers not found in 3d-store.js')
    with open(STORE_JS, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print('images with small copies:', len(sizes), '| new files written:', made)


if __name__ == '__main__':
    main()
